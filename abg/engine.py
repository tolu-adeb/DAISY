"""AnalysisEngine - the orchestrator every interface (CLI, API, notebooks) goes through.

Pipeline for ``analyze(symbol)``::

    ┌──────────── fetch stage (concurrent, each isolated) ─────────────┐
    │ history*  quote  news  fundamentals  options  benchmark-history  │   * only fatal one
    └──────────────────────────────┬───────────────────────────────────┘
                                   ▼
    compute stage (worker thread, pure functions):
        indicators → signal / regime / plays / levels → statistics
        → sentiment → options analytics (market or model chain)
        → feature vector (versioned schema)
                                   ▼
    risk stage: every registered RiskModel, concurrently, isolated
                                   ▼
    insight stage: Claude (cached, timeout) or rule-based fallback
                                   ▼
    report dict (JSON-safe) + provenance + warnings + per-stage timings

A failure in any non-history section becomes a ``warnings`` entry and that section is
``null`` - the report is still produced.  That is the core stability guarantee.
"""
